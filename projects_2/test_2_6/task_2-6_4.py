choice = input("Витязь, куда путь держишь? (направо/налево/прямо): ").strip().lower()

if choice == "направо" or choice == "право":
    print("Поедешь направо — коня потеряешь. Сам жив останешься, но пешим вернешься.")
elif choice == "налево" or choice == "лево":
    print("Поедешь налево — сам погибнешь. Конь твой останется жив и вернется домой один.")
elif choice == "прямо" or choice == "прямой":
    print("Поедешь прямо — женатым будешь. Найдешь счастье, но путь будет долгим.")
else:
    print("Стоишь на распутье. Выбери один из трех путей: направо, налево или прямо.")
